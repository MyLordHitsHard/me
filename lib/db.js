'use strict';
// Postgres data layer.
//  - DATABASE_URL set  → node-postgres pool (Neon, Supabase, RDS, local Postgres…)
//  - DATABASE_URL unset → PGlite, an embedded Postgres (zero-setup local dev / tests)
// Queries use `?` placeholders; they're rewritten to $1, $2… here.

const { ENTITIES } = require('./schema');

const SQL_TYPE = { text: 'TEXT', date: 'TEXT', enum: 'TEXT', int: 'INTEGER', bool: 'INTEGER', real: 'DOUBLE PRECISION', ref: 'INTEGER' };
// Timestamps are stored as UTC 'YYYY-MM-DD HH:MM:SS' text so the API format never changes.
const NOW = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

const q = (name) => `"${name}"`;

function toPg(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

// Wrap any client exposing query(text, params) → { rows, rowCount } with get/all/run.
function wrap(query) {
  const api = {
    query: (sql, params = []) => query(toPg(sql), params),
    async all(sql, ...params) { return (await api.query(sql, params)).rows; },
    async get(sql, ...params) { return (await api.query(sql, params)).rows[0]; },
    async run(sql, ...params) { const r = await api.query(sql, params); return { rowCount: r.rowCount, rows: r.rows }; },
  };
  return api;
}

async function connectPg(url) {
  const { Pool } = require('pg');
  const local = /localhost|127\.0\.0\.1|::1/.test(url) || /sslmode=disable/.test(url);
  const pool = new Pool({
    connectionString: url,
    ssl: local ? false : { rejectUnauthorized: true },
    max: Number(process.env.PG_POOL_MAX) || 5,
    idleTimeoutMillis: 60000, // keep warm connections across requests on a reused instance
    keepAlive: true,
    connectionTimeoutMillis: 15000, // Neon free tier may need a moment to wake up
  });
  const db = wrap((text, params) => pool.query(text, params));
  db.exec = (sql) => pool.query(sql);
  db.tx = async (fn) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const r = await fn(wrap((text, params) => client.query(text, params)));
      await client.query('COMMIT');
      return r;
    } catch (e) {
      await client.query('ROLLBACK').catch(() => {});
      throw e;
    } finally {
      client.release();
    }
  };
  db.close = () => pool.end();
  db.kind = 'postgres';
  return db;
}

async function connectPglite(dir) {
  const mod = '@electric-sql/pglite'; // kept dynamic so serverless bundlers don't ship it
  let PGlite;
  try {
    ({ PGlite } = await import(mod));
  } catch {
    throw new Error('No DATABASE_URL set and PGlite is not installed. Run `npm install` (dev dependencies) or set DATABASE_URL.');
  }
  if (dir !== 'memory://') require('node:fs').mkdirSync(dir, { recursive: true });
  const pg = new PGlite(dir === 'memory://' ? undefined : dir);
  await pg.waitReady;
  // PGlite runs one query at a time; serialise everything (transactions hold the lock).
  let chain = Promise.resolve();
  const lock = (fn) => { const r = chain.then(fn, fn); chain = r.catch(() => {}); return r; };
  const norm = (r) => ({ rows: r.rows, rowCount: r.affectedRows ?? r.rows.length });
  const db = wrap((text, params) => lock(() => pg.query(text, params).then(norm)));
  db.exec = (sql) => lock(() => pg.exec(sql));
  db.tx = (fn) => lock(() => pg.transaction((t) => fn(wrap((text, params) => t.query(text, params).then(norm)))));
  db.close = () => pg.close();
  db.kind = 'pglite';
  return db;
}

// Hash of the schema definition. Stored in the DB so cold starts skip migration with a single query.
const SCHEMA_VERSION = require('node:crypto').createHash('sha1').update(`v1:${JSON.stringify(ENTITIES)}`).digest('hex');

async function migrate(db) {
  try {
    const r = await db.get("SELECT value FROM lifeos_meta WHERE key = 'schema'");
    if (r && r.value === SCHEMA_VERSION) return;
  } catch { /* first run: meta table doesn't exist yet */ }
  await db.tx(async (t) => {
    // Serialise concurrent cold starts creating the schema.
    await t.query('SELECT pg_advisory_xact_lock(424242)');
    await t.query(`CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL UNIQUE,
      display_name TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      headline TEXT,
      bio TEXT,
      settings TEXT NOT NULL DEFAULT '{}',
      created_at TEXT NOT NULL DEFAULT ${NOW}
    )`);
    await t.query(`CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at BIGINT NOT NULL
    )`);
    await t.query(`CREATE TABLE IF NOT EXISTS links (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      from_type TEXT NOT NULL,
      from_id INTEGER NOT NULL,
      to_type TEXT NOT NULL,
      to_id INTEGER NOT NULL,
      label TEXT,
      created_at TEXT NOT NULL DEFAULT ${NOW}
    )`);
    await t.query('CREATE INDEX IF NOT EXISTS links_user ON links(user_id)');
    await t.query(`CREATE TABLE IF NOT EXISTS leaderboard_members (
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      board_key TEXT NOT NULL,
      joined_at TEXT NOT NULL DEFAULT ${NOW},
      PRIMARY KEY (user_id, board_key)
    )`);
    await t.query('CREATE INDEX IF NOT EXISTS lb_board ON leaderboard_members(board_key)');
    await t.query('CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id)');
    await t.query('CREATE TABLE IF NOT EXISTS lifeos_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL)');

    const existing = new Map();
    for (const r of await t.all("SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = current_schema()")) {
      if (!existing.has(r.table_name)) existing.set(r.table_name, new Set());
      existing.get(r.table_name).add(r.column_name);
    }
    for (const [table, def] of Object.entries(ENTITIES)) {
      if (!existing.has(table)) {
        const cols = Object.entries(def.fields).map(([n, f]) => `${q(n)} ${SQL_TYPE[f.type]}${f.type === 'ref' ? ` REFERENCES ${f.ref}(id) ON DELETE CASCADE` : ''}`);
        await t.query(`CREATE TABLE ${table} (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          ${cols.join(',\n          ')},
          created_at TEXT NOT NULL DEFAULT ${NOW},
          updated_at TEXT NOT NULL DEFAULT ${NOW}
        )`);
        await t.query(`CREATE INDEX IF NOT EXISTS ${table}_user ON ${table}(user_id)`);
        for (const [n, f] of Object.entries(def.fields)) {
          if (f.type === 'ref') await t.query(`CREATE INDEX IF NOT EXISTS ${table}_${n} ON ${table}(${q(n)})`);
        }
        continue;
      }
      // Lightweight migration: add columns introduced after the table was created.
      for (const [n, f] of Object.entries(def.fields)) {
        if (!existing.get(table).has(n)) await t.query(`ALTER TABLE ${table} ADD COLUMN ${q(n)} ${SQL_TYPE[f.type]}`);
      }
    }
    await t.query("INSERT INTO lifeos_meta (key, value) VALUES ('schema', $1) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value", [SCHEMA_VERSION]);
  });
}

async function open() {
  const url = process.env.DATABASE_URL || process.env.POSTGRES_URL;
  const db = url ? await connectPg(url) : await connectPglite(process.env.PGLITE_DIR || require('node:path').join(__dirname, '..', 'data', 'pglite'));
  await migrate(db);
  return db;
}

// Same normalisation as lib/leaderboards.js norm(): trim, lowercase, collapse whitespace.
const NORM = (col) => `regexp_replace(lower(trim(${col})), '\\s+', ' ', 'g')`;

module.exports = { open, NOW, NORM, q };
